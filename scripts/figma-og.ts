/**
 * figma-og — puts the OG card templates into the round trip.
 *
 * Same split as `figma-push.ts` and `figma-page.ts`: this file decides *what*
 * Figma should hold and emits a self-contained program that makes it so,
 * `use_figma` runs it, and `--record` folds the returned ids back into
 * `figma/sync.json`. Everything above the transport is tested offline in
 * `figma/og.ts`.
 *
 * What makes this one different is that a card has two halves travelling in
 * opposite directions. The artwork only ever goes *out*: it is a three.js
 * render, Figma cannot produce one, and the push therefore places it as an
 * image and never reads it back. The spec only ever comes *in*: a dozen fields
 * a designer can edit on the card in Figma, which `--pull` reconciles against
 * `og/specs/*.json` exactly the way the token pull reconciles colours.
 *
 * The bytes of the artwork are the one thing this script cannot deliver
 * itself — the plugin sandbox has no network back to this repo, and inlining
 * 2.6 MB of JPEG into the program is not an option — so the image travels
 * through `upload_assets`, addressed to the `art` node id the push hands back.
 * That is why uploading is its own step with its own flag.
 *
 *   pnpm figma:og                    # emit dist/figma-og.{js,json} + a summary
 *   pnpm figma:og --snapshot         # also emit the read-back program
 *   pnpm figma:og --record out.json  # fold the ids in, print the upload plan
 *   pnpm figma:og --uploaded         # stamp the artwork as landed
 *   pnpm figma:og --pull snap.json [--prefer=code|figma] [--apply]
 */
