/**
 * figma-template — puts the card's *layout* into the round trip.
 *
 * `figma-og.ts` sends fourteen cards and brings back what they say.  This sends
 * one frame and brings back where they say it: drag the message block in Figma,
 * pull, and `og/layout/card.json` moves — so the next render of every card
 * moves with it.
 *
 * The template is drawn at the reference box the layout is authored against, so
 * Figma's inspector and the JSON hold the same numbers. It carries the
 * reference card's own render as a backdrop, because type is only judgeable
 * over the artwork it has to stay legible on — and that artwork is the one
 * thing in this whole system Figma cannot produce.
 *
 *   pnpm figma:template                  # dist/figma-template.js + a summary
 *   pnpm figma:template --snapshot       # also the read-back program
 *   pnpm figma:template --record out.json
 *   pnpm figma:template --pull snap.json [--prefer=code|figma] [--apply]
 */
