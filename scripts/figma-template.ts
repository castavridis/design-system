async function readLayout() {
	return JSON.parse(await readFile(LAYOUT_PATH, 'utf8')) as Layout
}

function renderReport(id: string, entries: Entry[], policy: Policy, applied: boolean) {
	const counts = summarise(entries)
	const lines = [
		`# Layout sync ${id}`,
		'',
		`Direction: Figma -> code. ${entries.length} entr${entries.length === 1 ? 'y' : 'ies'}.`,
		'',
		'| outcome | count |',
		'| --- | --- |',
		...Object.entries(counts).map(([k, n]) => `| ${k} | ${n} |`),
		'',
	]

	const label = (key: string) => `\`${key.slice(`${SCOPE}.`.length)}\`${isGeometry(key) ? ' _(dragged)_' : ''}`

	const section = (title: string, kinds: string[], body: (e: Entry) => string) => {
		const hits = entries.filter((e) => kinds.includes(e.verdict.kind))
		if (!hits.length) return
		lines.push(`## ${title}`, '')
		for (const e of hits) lines.push(`- ${body(e)}`)
		lines.push('')
	}

	section('Pulled from Figma', ['pull'], (e) => {
		const v = e.verdict as { kind: 'pull'; value: string }
		return `${label(e.key)} -> \`${v.value || '(none)'}\``
	})
	section('Resolved by policy', ['resolved'], (e) => {
		const v = e.verdict as { kind: 'resolved'; winner: string; ours: string; theirs: string }
		return `${label(e.key)}: code \`${v.ours}\` vs Figma \`${v.theirs}\` — **${v.winner}** won`
	})
	section('Conflicts — need a decision', ['conflict'], (e) => {
		const v = e.verdict as { kind: 'conflict'; ours: string; theirs: string }
		return `${label(e.key)}: code \`${v.ours}\` vs Figma \`${v.theirs}\``
	})
	section('Only in the layout', ['create'], (e) => `${label(e.key)} — push to draw it`)
	section('Only in Figma', ['orphan'], (e) => `${label(e.key)} — no such field in og/layout/card.json`)

	lines.push(
		'',
		'A layout change moves every card. Re-render with `pnpm og:demo` afterwards,',
		'then `pnpm figma:og` to send the new artwork back.',
		'',
		applied ? 'Edits were applied to `og/layout/card.json`.' : 'No files were changed. Re-run with `--apply` to write them.',
		'',
	)
	return lines.join('\n')
}

async function main() {
	const state = (await readState()) as StateWithTemplate
	const layout = await readLayout()
	const values = flatten(layout)

	const record = flag('record')
	if (record) {
		const result = JSON.parse(await readFile(resolve(process.cwd(), record), 'utf8')) as {
			pageId: string
			frameId: string
			panelId?: string
			problems?: string[]
			missingVariables?: string[]
			missingFonts?: string[]
		}

		state.template = {
			pageId: result.pageId,
			frameId: result.frameId,
			...(result.panelId ? { panelId: result.panelId } : {}),
		}

		/* Same reason as the card push: a push makes both sides agree, so the
		   values it wrote are the base the next diff measures movement against. */
		const entries: Entry[] = Object.entries(values).map(([key, value]) => ({ key, verdict: { kind: 'push', value } }))
		state.lastSync = {
			syncId: syncId(new Date()),
			at: new Date().toISOString(),
			values: nextBase(state.lastSync?.values ?? {}, entries),
		}
		state.prefer = { [SCOPE]: 'ask', ...state.prefer }

		await writeState(state)
		console.log(`figma-template: recorded frame ${result.frameId} -> figma/sync.json`)
		console.log(`  base advanced with ${entries.length} layout values`)
		for (const problem of result.problems ?? []) console.log(`  ! ${problem}`)
		for (const name of result.missingVariables ?? []) console.log(`  ! no variable named ${name}`)
		for (const name of result.missingFonts ?? []) console.log(`  ! font unavailable: ${name}`)
		console.log(`\nUpload the backdrop with upload_assets: ${SAMPLE.art} -> the frame's \`art\` node`)
		return
	}

	const pull = flag('pull')
	if (pull) {
		const snapshot = JSON.parse(await readFile(resolve(process.cwd(), pull), 'utf8')) as {
			values: Values
			missing?: string[]
			notes?: string[]
		}

		const override = flag('prefer') as 'code' | 'figma' | undefined
		if (override && override !== 'code' && override !== 'figma') {
			throw new Error(`--prefer must be code or figma, received "${override}"`)
		}

		const policy: Policy = {
			prefer: state.prefer,
			derived: state.derived,
			...(override ? { override } : {}),
		}

		const entries = reconcile(state.lastSync?.values ?? {}, values, snapshot.values, policy)
		const id = syncId(new Date())
		const apply = has('apply')

		const report = renderReport(id, entries, policy, apply)
		const out = reportPath(id)
		await mkdir(dirname(out), { recursive: true })
		await writeFile(out, report, 'utf8')

		if (apply) {
			const edits = entries.flatMap((entry) => {
				if (entry.verdict.kind === 'pull') return [{ key: entry.key, value: entry.verdict.value }]
				if (entry.verdict.kind === 'resolved' && entry.verdict.winner === 'figma') {
					return [{ key: entry.key, value: entry.verdict.value }]
				}
				return []
			})

			if (edits.length) {
				await writeFile(LAYOUT_PATH, applyEdits(await readFile(LAYOUT_PATH, 'utf8'), edits), 'utf8')
				console.log(`  wrote ${edits.length} value(s) -> og/layout/card.json`)
			}

			state.lastSync = {
				syncId: id,
				at: new Date().toISOString(),
				values: nextBase(state.lastSync?.values ?? {}, entries),
			}
			await writeState(state)
		}

		const counts = summarise(entries)
		console.log(`figma-template: ${entries.length} entries -> ${out}`)
		for (const [kind, n] of Object.entries(counts)) console.log(`  ${kind}: ${n}`)
		if (!entries.length) console.log('  no drift')
		for (const key of snapshot.missing ?? []) console.log(`  ! ${key} was not found in the template`)
		for (const note of snapshot.notes ?? []) console.log(`  ! ${note}`)
		if (!apply && entries.length) console.log('\nDry run. Re-run with --apply to write the layout and advance the base.')
		if (apply && entries.length) console.log('\nRe-render with `pnpm og:demo` — the layout moved, so every card did.')

		if (entries.some((e) => e.verdict.kind === 'conflict')) process.exitCode = 1
		return
	}

	const where: Target = {
		pageId: state.template?.pageId ?? state.og?.pageId ?? flag('page') ?? state.pageId,
		...(state.template?.frameId ? { frameId: state.template.frameId } : {}),
	}

	/* Only the keys geometry cannot express become typed rows. */
	const fields = Object.fromEntries(Object.entries(values).filter(([key]) => !isGeometry(key)))

	await mkdir(dirname(OUT_PATH), { recursive: true })
	await writeFile(OUT_PATH, pluginScript(layout, fields, where), 'utf8')
	if (has('snapshot')) await writeFile(SNAPSHOT_PATH, snapshotScript(layout, Object.keys(values), where), 'utf8')

	console.log(describe(values))
	console.log(`  reference box ${layout.reference.width}×${layout.reference.height}`)
	console.log(`\nfigma-template: ${OUT_PATH.replace(`${process.cwd()}/`, '')}`)
	console.log(`  file ${state.fileKey}, page ${where.pageId}, frame "${FRAME_NAME}" ${where.frameId ?? '(new)'}`)
	console.log(`\nRun ${join('dist', 'figma-template.js')} via use_figma, then:`)
	console.log(`  pnpm figma:template --record <result.json>`)
}

await main()
